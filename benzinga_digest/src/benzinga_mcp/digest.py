# ── UPDATED 检测 / 缓存失效 (Benzinga 改稿:同 NodeID, CreatedAt 不变, UpdatedAt 推进) ──
def _split_new_vs_updated(by_id: dict, metas: list,
                          seen: dict | None = None,
                          extra_filter=None) -> tuple[list, list]:
    """把抓到的 raw 切成两路:
      new     : 全新 id (本日 metas 没,seen_store 也没) → 走原渲染+追加路径
      updated : 同 id 已在本日 metas, 但 UpdatedAt 严格更晚 → 重渲覆盖
    其他情形(同 id 但 UpdatedAt 未变 / 仅在 seen_store 不在 metas)一律跳过,
    避免把跨天文章的更新混进今天的文件。

    extra_filter(it) -> bool: 调用方额外过滤(is_noise / sentiment_only).
    返回 (new_list, updated_list)。"""
    today_idx = {m["id"]: m for m in metas}
    seen = seen if seen is not None else {}
    new_list, updated_list = [], []
    for nid, it in by_id.items():
        if extra_filter and not extra_filter(it):
            continue
        new_u = (it.get("UpdatedAt") or "").strip()
        if nid in today_idx:
            prev = (today_idx[nid].get("updated_at")
                    or today_idx[nid].get("ts") or "")
            if new_u and new_u > prev:
                updated_list.append(it)
            # else 同条目, 没变 → 跳过
        elif nid in seen:
            # 跨天旧文章:不混进今天的文件
            continue
        else:
            new_list.append(it)
    return new_list, updated_list


def _apply_updated_metas(metas: list, updated_metas: list,
                         date_str: str, run_hhmm: str = "") -> int:
    """把 UPDATED 重渲后的 meta 原位覆盖 metas[i],并失效该 id 的翻译 + 当天 AI 总结缓存。
    要求 updated_metas 与 metas 通过 id 匹配;没匹配到的当作新增追加。返回成功覆盖数。"""
    by_pos = {m["id"]: i for i, m in enumerate(metas)}
    n = 0
    affected_ids: list[str] = []
    appended_new: list[dict] = []
    for m in updated_metas:
        nid = m["id"]
        if run_hhmm:
            m["added"] = run_hhmm
        m["updated"] = True
        if nid in by_pos:
            old = metas[by_pos[nid]]
            # 保留原 added (首次抓到的 hh:mm) — 便于日后追溯"原条目何时落库"
            m.setdefault("first_added", old.get("first_added") or old.get("added") or "")
            metas[by_pos[nid]] = m
            n += 1
            affected_ids.append(nid)
        else:
            # 兜底:meta 已被外部清理但 by_id 还能匹配到 UPDATED — 当作新增追加
            appended_new.append(m)
    metas.extend(appended_new)
    if affected_ids:
        _invalidate_tr_cache(date_str, affected_ids)
        _invalidate_aisum_cache(date_str)
    return n


def _invalidate_tr_cache(date_str: str, ids: list[str]) -> None:
    """删 .tr.json[id] —— UPDATED 文章下次取标题/正文翻译时强制重译。"""
    def _mut(cache: dict) -> None:
        for k in ids:
            cache.pop(str(k), None)
    try:
        tr_update(date_str, _mut)
    except Exception:
        pass  # 缓存失效失败不致命, 下次会再尝试


def _invalidate_aisum_cache(date_str: str) -> None:
    """删 ai_summary/<date>*.json (主摘要 + 所有 scope 子集) —— 任一文章更新都让当天 AI 总结作废。"""
    base = PROJECT / "ai_summary"
    if not base.exists():
        return
    for f in list(base.glob(f"{date_str}*.json")):
        try:
            f.unlink()
        except Exception:
            pass


def _acquire_lock() -> bool:
    DIGEST_DIR.mkdir(parents=True, exist_ok=True)
    if LOCK_PATH.exists():
        try:
            age = time.time() - LOCK_PATH.stat().st_mtime
        except OSError:
            age = 0
        if age < LOCK_STALE_SEC:
            return False
    LOCK_PATH.write_text(str(os.getpid()))
    return True


_SENT_MIN = int(os.environ.get("BENZINGA_SENT_MIN", "2"))  # 历史保留 |sentiment|>=此值(0=中性,1=弱,2+=强)
# 默认 2(强sentiment): 全量非0(|s|>=1)约2万条要18-36h不现实; |s|>=2约1400条~1.5h且更高信念。


def _has_sentiment(s) -> bool:
    """有(非中性)sentiment? 数字: |s|>=_SENT_MIN; 字符串: 非空且非 Neutral。"""
    if s is None or s == "":
        return False
    try:
        return abs(int(s)) >= _SENT_MIN
    except (TypeError, ValueError):
        return str(s).strip().lower() not in ("", "0", "neutral", "none")


def backfill_day_rows(date_str: str, items: list, sentiment_only: bool = True) -> dict:
    """用已有 items(如从本地 parquet 映射来的)回填某天，不走 WS。复用翻译/写盘逻辑。
    items 每条形如 {ID,Title,CreatedAt,Body,Tickers:[{name}],Sentiment,...}。"""
    if not _acquire_lock():
        return {"status": "locked", "added": 0, "message": "已有运行中，跳过。"}
    try:
        by_id: dict[str, dict] = {}
        for it in items:
            by_id.setdefault(str(it.get("ID") or it.get("NodeID")), it)
        md_path, js_path = _day_paths(date_str)
        metas = _load_day(js_path)
        have = {m["id"] for m in metas}
        kept = [it for nid, it in by_id.items()
                if nid not in have and not is_noise(it.get("Title") or "")
                and (not sentiment_only or _has_sentiment(it.get("Sentiment")))]
        kept.sort(key=lambda x: x.get("CreatedAt") or "", reverse=True)
        new_metas: list[dict] = []
        if kept:
            workers = max(1, min(TR_PARALLEL, len(kept)))
            with ThreadPoolExecutor(max_workers=workers) as ex:
                new_metas = list(ex.map(_render, kept))
            run_hhmm = datetime.now().astimezone().strftime("%H:%M")
            for m in new_metas:
                m["added"] = run_hhmm
            metas = metas + new_metas
            _save_day(js_path, metas)
            if WRITE_MD: md_path.write_text(_build_md(date_str, metas), encoding="utf-8")  # .md 默认关闭
        return {"status": "ok", "date": date_str, "added": len(new_metas),
                "total": len(metas), "file": str(md_path),
                "message": f"{date_str} parquet +{len(new_metas)}（共 {len(metas)}）"}
    finally:
        try:
            LOCK_PATH.unlink()
        except OSError:
            pass


def _meta_fields(it: dict) -> dict:
    """从原始 WS item 抽取**全部元数据(不含正文 Body)**：
    channels(分类) + 完整 ticker/quote/channel 对象 + teaser + type + meta_raw 兜底。
    meta_raw 保留除 Body 外的所有原始字段，保证以后任何新字段都不会再丢。"""
    channels_full = [c for c in (it.get("Channels") or []) if isinstance(c, dict)]
    channels = [c.get("name") for c in channels_full if c.get("name")]
    tickers_full = [t for t in (it.get("Tickers") or []) if isinstance(t, dict)]
    quotes_full = [q for q in (it.get("Quotes") or []) if isinstance(q, dict)]
    teaser = html.unescape(it.get("TeaserText") or "").strip()
    meta_raw = {k: v for k, v in it.items() if k != "Body"}
    return {"channels": channels, "channels_full": channels_full,
            "tickers_full": tickers_full, "quotes_full": quotes_full,
            "teaser": teaser, "type": it.get("Type"), "meta_raw": meta_raw}


def _build_block(m: dict) -> str:
    """从已结构化的 meta 重建 markdown 块（含 Channels/Teaser）。供 _render_raw 与元数据回填共用。"""
    nid = str(m.get("id"))
    L = [f'<a id="{_anchor(nid)}"></a>', f"## [{m.get('hhmm','')}] {m.get('title','')} <!-- id:{nid} -->"]
    if m.get("channels"):
        L.append(f"**🗂 Channels**：{' · '.join(m['channels'][:12])}")
    if m.get("tickers"):
        L.append(f"**🏷 Tickers**：{' · '.join(m['tickers'][:12])}")
    if m.get("quotes"):
        L.append(f"**💹 Quote**：{' · '.join(m['quotes'][:12])}")
    if m.get("teaser"):
        L.append(f"> {m['teaser']}")
    if m.get("links"):
        L.append(f"**🔗 Links**：{' '.join(m['links'][:12])}")
    for u in (m.get("images") or [])[:6]:
        L.append(f"![]({u})")
    L.append("")
    paras = [(p.get("cn") or p.get("en")) for p in (m.get("paras") or []) if (p.get("cn") or p.get("en"))]
    L.append("\n\n".join(paras) if paras else "(no body)")
    L += ["", "[↑ back](#toc)", "", "---", ""]
    return "\n".join(L)


def _render_raw(it: dict) -> dict:
    """不翻译：存英文原文 + 图片 + 链接 + **全部元数据**(channels/tickers/quotes/teaser/type/sentiment)。
    英文放 paras 的 cn 槽以便 PWA 默认显示。"""
    nid = str(it.get("NodeID") or it.get("ID"))
    title_en = html.unescape(it.get("Title") or "")
    hhmm = local_hhmm(it.get("CreatedAt") or "")
    tick_syms = [t["name"] for t in (it.get("Tickers") or [])
                 if isinstance(t, dict) and t.get("name")]
    quotes = [fmt_quote(q) for q in (it.get("Quotes") or []) if isinstance(q, dict)]
    body_html = it.get("Body") or ""
    images = extract_images(body_html)
    links = extract_links(body_html)
    body_text = trim_promo(html_to_text(body_html))
    paras_en = [p.strip() for p in re.split(r"\n\s*\n", body_text) if p.strip()]
    if not paras_en and body_text.strip():
        paras_en = [body_text.strip()]
    paras = [{"cn": p, "en": ""} for p in paras_en]  # 英文放显示槽(无需翻译)
    m = {"id": nid, "ts": it.get("CreatedAt") or "",
         "updated_at": it.get("UpdatedAt") or "",
         "hhmm": hhmm,
         "title": title_en, "title_en": title_en, "tickers": tick_syms[:8],
         "quotes": quotes[:12], "images": images[:8], "links": links[:12],
         "sentiment": it.get("Sentiment"), "paras": paras}
    m.update(_meta_fields(it))      # channels / *_full / teaser / type / meta_raw
    m["block"] = _build_block(m)
    return m


