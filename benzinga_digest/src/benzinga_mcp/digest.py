def tr_update(date_str: str, mutate):
    """flock 串行地 读-改-写 .<date>.tr.json（标题/正文/按需 三处写共用一把锁，
    避免并发互相覆盖 t/b 字段）。mutate(cache:dict) 原地修改；返回更新后的 cache。"""
    import fcntl
    DIGEST_DIR.mkdir(parents=True, exist_ok=True)
    p = DIGEST_DIR / date_str[:7] / f".{date_str}.tr.json"
    p.parent.mkdir(parents=True, exist_ok=True)
    with open(_TR_LOCK, "w") as lk:
        fcntl.flock(lk, fcntl.LOCK_EX)
        try:
            try:
                cache = json.loads(p.read_text(encoding="utf-8"))
            except Exception:
                cache = {}
            mutate(cache)
            tmp = p.with_suffix(".tmp")
            tmp.write_text(json.dumps(cache, ensure_ascii=False), encoding="utf-8")
            os.replace(tmp, p)
            return cache
        finally:
            fcntl.flock(lk, fcntl.LOCK_UN)

