def translate_status() -> dict:
    """各翻译源当前状态(给前端「翻译源」图标)。current=下一次翻译会先用哪家。"""
    now = time.time()
    provs = []
    for p in ("google", "bing", "argos"):
        err = _tr_lasterr.get(p)
        cd = _tr_cooldown.get(p, 0)
        provs.append({
            "id": p, "label": _TR_LABEL[p], "role": _TR_ROLE[p],
            "remote": p in ("google", "bing"),
            "cooled": cd > now, "cooldown_left": max(0, int(cd - now)),
            "last_err": (err[1] if err else ""),
            "last_ok": bool(err and not err[1]),
            "tested": bool(err),
        })
    def _ok(p):
        if _tr_cooldown.get(p, 0) > now:
            return False
        e = _tr_lasterr.get(p)
        return not (e and e[1])           # 没冷却 + 上次没报错 = 健康
    nxt = _TR_PRIMARIES[_tr_turn[0] % len(_TR_PRIMARIES)]   # 轮到谁当首选
    if _tr_cooldown.get(nxt, 0) > now:                      # 但它若在冷却,真实代码会跳到下一个健康家
        nxt = next((p for p in _TR_ALL if _ok(p)), nxt)
    cur = _TR_LABEL.get(nxt, nxt)
    return {"providers": provs, "current": cur}


def translate_test(provider: str) -> dict:
    """实测某一家(翻一句样本)→ {ok, text/error, ms}。给前端「点哪家看为啥不行」。"""
    sample = "The company reported strong quarterly results and raised its full-year guidance."
    t0 = time.time()
    zh = None
    if provider == "argos":
        r = _argos_translate([sample]); zh = r[0] if r else None
    elif provider in _TR_FNS:
        r = _TR_FNS[provider]([sample]); zh = r[0] if r else None
    else:
        return {"ok": False, "error": "未知翻译源"}
    ms = int((time.time() - t0) * 1000)
    if zh and any("一" <= c <= "鿿" for c in zh):
        return {"ok": True, "text": zh, "ms": ms, "label": _TR_LABEL.get(provider, provider)}
    return {"ok": False, "ms": ms, "label": _TR_LABEL.get(provider, provider),
            "error": (_tr_lasterr.get(provider, (0, ""))[1] or "翻译失败 / 无中文输出")}


def fmt_quote(q: dict) -> str:
    sym, px, vol = q.get("symbol"), q.get("price"), q.get("volume")
    try:
        px = f"${float(px):,.2f}"
    except (TypeError, ValueError):
        px = "?"
    try:
        vol = f"量{int(vol):,}"
    except (TypeError, ValueError):
        vol = ""
    return f"{sym} {px}{(' ' + vol) if vol else ''}".strip()


