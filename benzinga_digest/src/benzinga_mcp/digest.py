def backfill_meta_range(start_ds: str, end_ds: str) -> dict:
    """批量元数据回填：**一次 WS 查询覆盖 [start_ds, end_ds] 多天**（摊薄握手开销、
    更少握手 → 更低 429 风险），按 ET 日期分桶后合并进各天已存文章。
    返回 {status, days:{ds:{updated,total,exists}}}。建议批宽 ≤5 天(单批 < limit)。"""
    if not _acquire_lock():
        return {"status": "locked", "days": {}, "message": "已有运行中，跳过。"}
    try:
        et = ZoneInfo("America/New_York")
        d0 = datetime.strptime(start_ds, "%Y-%m-%d").replace(tzinfo=et)
        d1 = datetime.strptime(end_ds, "%Y-%m-%d").replace(tzinfo=et)
        since = d0.astimezone(timezone.utc)
        until = (d1 + timedelta(days=1)).astimezone(timezone.utc)
        raw = asyncio.run(news_query_multi(
            types=EDITORIAL_TYPES, since_utc=since, until_utc=until,
            limit=6000, max_pages=80, sentiments=None, include_body=False))
        # 按 ET 日期分桶 → {ds: {id: item}}
        by_day: dict[str, dict] = {}
        for it in raw:
            ca = it.get("CreatedAt") or ""
            try:
                dtu = datetime.fromisoformat(ca.replace("Z", "+00:00"))
                if dtu.tzinfo is None:
                    dtu = dtu.replace(tzinfo=timezone.utc)
                ds = dtu.astimezone(et).date().isoformat()
            except Exception:
                continue
            by_day.setdefault(ds, {})[str(it.get("NodeID") or it.get("ID"))] = it
        out: dict[str, dict] = {}
        cur = d0.date()
        while cur <= d1.date():
            ds = cur.isoformat()
            cur = cur + timedelta(days=1)
            md_path, js_path = _day_paths(ds)
            metas = _load_day(js_path)
            if not metas:
                out[ds] = {"updated": 0, "total": 0, "exists": False}
                continue
            bid = by_day.get(ds, {})
            upd = 0
            for m in metas:
                it = bid.get(str(m.get("id")))
                if not it:
                    continue
                m.update(_meta_fields(it))
                if m.get("sentiment") is None and it.get("Sentiment") is not None:
                    m["sentiment"] = it.get("Sentiment")
                m["block"] = _build_block(m)
                upd += 1
            _save_day(js_path, metas)
            if WRITE_MD: md_path.write_text(_build_md(ds, metas), encoding="utf-8")  # .md 默认关闭
            out[ds] = {"updated": upd, "total": len(metas), "exists": True}
        return {"status": "ok", "days": out,
                "message": f"{start_ds}..{end_ds} 批量元数据 {sum(v['updated'] for v in out.values())} 条"}
    finally:
        try:
            LOCK_PATH.unlink()
        except OSError:
            pass


def _render(it: dict) -> dict:
    """翻译一篇，返回 meta dict（含可跳转锚点的 markdown 块）。"""
    nid = str(it.get("NodeID") or it.get("ID"))
    title_en = html.unescape(it.get("Title") or "")
    hhmm = local_hhmm(it.get("CreatedAt") or "")

    tick_strs, tick_syms = [], []
    for t in (it.get("Tickers") or []):
        if isinstance(t, dict) and t.get("name"):
            tick_syms.append(t["name"])
            desc = t.get("description")
            tick_strs.append(f"{t['name']}（{desc}）" if desc else t["name"])
    quotes = [fmt_quote(q) for q in (it.get("Quotes") or []) if isinstance(q, dict)]
    channels = [c.get("name") for c in (it.get("Channels") or [])
                if isinstance(c, dict) and c.get("name")]
    body_html = it.get("Body") or ""
    images = extract_images(body_html)
    links = extract_links(body_html)
    # 段落级翻译：拆段逐段翻，保留 EN/CN 对齐供 PWA 双语视图（默认中文，可切双语）。
    body_text = trim_promo(html_to_text(body_html))
    paras_en = [p.strip() for p in re.split(r"\n\s*\n", body_text) if p.strip()]
    if not paras_en and body_text.strip():
        paras_en = [body_text.strip()]
    _MAXP = 14  # 限制单篇段数, 控翻译开销
    if len(paras_en) > _MAXP:
        paras_en = paras_en[:_MAXP - 1] + ["\n\n".join(paras_en[_MAXP - 1:])]
    # 标题 + 正文段一起送多源翻译(remote → argos 轻量本地;**已去掉 qwen,不再转风扇**)
    _src = ([title_en] if title_en else []) + paras_en
    _tr = translate_lines(_src) if _src else []
    title_cn = ((_tr[0] if _tr else title_en) if title_en else "")
    _off = 1 if title_en else 0
    paras = [{"en": p, "cn": (_tr[_off + k] if _off + k < len(_tr) else p)} for k, p in enumerate(paras_en)]
    body_cn = "\n\n".join(x["cn"] for x in paras)

    L = [f'<a id="{_anchor(nid)}"></a>',
         f"## [{hhmm}] {title_cn} <!-- id:{nid} -->",
         f"<sub>{title_en}</sub>"]
    if tick_strs:
        L.append(f"**🏷 标的**：{' · '.join(tick_strs[:12])}")
    if quotes:
        L.append(f"**💹 报价**：{' · '.join(quotes[:12])}")
    if channels:
        L.append(f"**📂 频道**：{' / '.join(channels[:8])}")
    if links:
        L.append(f"**🔗 链接**：{' '.join(links)}")
    for u in images[:4]:
        L.append(f"![]({u})")
    L.append("")
    L.append(body_cn if body_cn else "（无正文）")
    L += ["", "[↑ 回目录](#toc)", "", "---", ""]
    return {"id": nid, "ts": it.get("CreatedAt") or "",
            "updated_at": it.get("UpdatedAt") or "",
            "hhmm": hhmm,
            "title": title_cn, "title_en": title_en, "tickers": tick_syms[:8],
            "quotes": quotes[:12], "paras": paras, "block": "\n".join(L)}


def run_digest(limit: int | None = None, hours: int = 24, open_file: bool = False) -> dict:
    """
    跑一次增量 digest，返回结果 dict：
      {status, added, updated, batch_seen, marked, file, items[], section_md, message}
    status: "ok" | "locked"

    UPDATED 检测: Benzinga 改稿同 NodeID, CreatedAt 不变, UpdatedAt 推进
    → 走 `_apply_updated_metas` 原位覆盖 + 失效 .tr.json + ai_summary 缓存。
    """
    if not _acquire_lock():
        return {"status": "locked", "added": 0, "message": "已有运行中（.run.lock 未过期），本次跳过。"}
    try:
        now = datetime.now().astimezone()
        date_str = now.strftime("%Y-%m-%d")
        md_path, js_path = _day_paths(date_str)

        metas = _load_day(js_path)
        seen = seen_store.load_seen()

        raw = asyncio.run(_fetch(hours))
        by_id: dict[str, dict] = {}
        # 多个推送同 id 取 UpdatedAt 最新的(避免一次抓的 batch 内自己挡自己)
        for it in raw:
            nid = str(it.get("NodeID") or it.get("ID"))
            cur = by_id.get(nid)
            if cur is None:
                by_id[nid] = it
            else:
                cur_u = cur.get("UpdatedAt") or cur.get("CreatedAt") or ""
                new_u = it.get("UpdatedAt") or it.get("CreatedAt") or ""
                if new_u > cur_u:
                    by_id[nid] = it
        all_ids = list(by_id.keys())

        new_kept, updated_kept = _split_new_vs_updated(
            by_id, metas, seen=seen,
            extra_filter=lambda x: not is_noise(x.get("Title") or ""),
        )
        new_kept.sort(key=lambda x: x.get("CreatedAt") or "", reverse=True)
        if limit:
            new_kept = new_kept[:limit]

        run_hhmm = now.strftime("%H:%M")
        new_metas: list[dict] = []
        if new_kept:
            workers = max(1, min(TR_PARALLEL, len(new_kept)))
            with ThreadPoolExecutor(max_workers=workers) as ex:
                new_metas = list(ex.map(_render, new_kept))
            for m in new_metas:
                m["added"] = run_hhmm

        updated_count = 0
        if updated_kept:
            workers = max(1, min(TR_PARALLEL, len(updated_kept)))
            with ThreadPoolExecutor(max_workers=workers) as ex:
                updated_metas = list(ex.map(_render, updated_kept))
            updated_count = _apply_updated_metas(metas, updated_metas, date_str, run_hhmm)

        if new_metas or updated_count:
            if new_metas:
                metas = metas + new_metas
            _save_day(js_path, metas)
            if WRITE_MD: md_path.write_text(_build_md(date_str, metas), encoding="utf-8")  # .md 默认关闭

        # seen_store 按 (id, UpdatedAt) 计入: UPDATED 也要把存储的 UpdatedAt 推进, 防下次再触发
        marked = seen_store.mark_seen_updated(
            {nid: by_id[nid].get("UpdatedAt") or "" for nid in all_ids})
        seen_store.prune(max_age_days=14)

        msg_parts = [f"新增 {len(new_metas)} 条"]
        if updated_count:
            msg_parts.append(f"更新 {updated_count} 条")
        msg_parts.append(f"本批已读 {len(all_ids)} / 新标记 {marked}")
        return {
            "status": "ok",
            "added": len(new_metas),
            "updated": updated_count,
            "batch_seen": len(all_ids),
            "marked": marked,
            "file": str(md_path),
            "items": [{"time": m["hhmm"], "title": m["title"], "tickers": m["tickers"]}
                      for m in new_metas],
            "message": f"{'(' + ', '.join(msg_parts) + ')'} -> {md_path}",
        }
    finally:
        try:
            LOCK_PATH.unlink()
        except OSError:
            pass


