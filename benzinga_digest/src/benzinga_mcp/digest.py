def _load_day(js_path: Path) -> list[dict]:
    """读某天原始 list。优先普通 .json(daemon 写今天/昨天用);compact 把旧日子压成
    .json.zst 后回退解压它(无损),保证 backfill 读旧日合并不丢数据。"""
    try:
        if js_path.exists():
            data = json.loads(js_path.read_text(encoding="utf-8"))
        else:
            zp = js_path.parent / (js_path.name + ".zst")
            if not zp.exists():
                return []
            import zstandard as _zstd
            data = json.loads(_zstd.ZstdDecompressor().decompress(zp.read_bytes()))
        return data if isinstance(data, list) else []
    except Exception:
        return []


def _save_day(js_path: Path, metas: list[dict]) -> None:
    js_path.parent.mkdir(parents=True, exist_ok=True)
    tmp = js_path.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(metas, ensure_ascii=False), encoding="utf-8")
    os.replace(tmp, js_path)


def _anchor(nid: str) -> str:
    return f"a{nid}"


def _build_md(date_str: str, metas: list[dict]) -> str:
    """重建整天文件：更新记录 + 可点击目录 + 全部文章正文（时间倒序）。

    每篇带「加入时间节点」(added)；最近一批标 🆕，方便区分哪些是上次之后新增的。
    """
    metas = sorted(metas, key=lambda m: m.get("ts") or "", reverse=True)
    batches = Counter(m.get("added", "") for m in metas if m.get("added"))
    batch_times = sorted(batches)
    latest = batch_times[-1] if batch_times else None
    upd = " · ".join(f"{t}(+{batches[t]})" for t in batch_times)

    L = [f"# Benzinga Digest {date_str}（{len(metas)} 条）", "",
         "> 全文中文机翻（qwen2.5:3b）· 点目录标题跳到文章 · 时间倒序 · 本地时间", ""]
    if upd:
        L += [f"🕑 **更新记录**：{upd}　（🆕 = 最近一次新增）", ""]
    L += ['<a id="toc"></a>', "## 📑 目录", ""]
    for m in metas:
        flag = "🆕 " if (latest and m.get("added") == latest) else ""
        addtag = f"　·加于{m['added']}" if m.get("added") else ""
        tk = ("　" + " ".join(m.get("tickers", [])[:4])) if m.get("tickers") else ""
        L.append(f"- {flag}`{m.get('hhmm','')}` [{m.get('title','')}](#{_anchor(m['id'])}){tk}{addtag}")
    L += ["", "---", ""]
    for m in metas:
        L.append(m.get("block", ""))
    return "\n".join(L)


def backfill_day(date_str: str, open_file: bool = False, sentiment_only: bool = False,
                 translate: bool = True) -> dict:
    """补全某一自然日（美东日历日）的完整 digest -> digests/<月>/<date>.md。

    sentiment_only=True 时只保留带 Sentiment 标签的文章。
    translate=False 时不翻译(用 _render_raw 存英文原文+图片+链接+meta，作者自行翻译)。

    UPDATED 检测同 run_digest: 同 NodeID + UpdatedAt 推进 → 原位覆盖 + 缓存失效。
    daemon 的稳态循环(每小时重跑今天+昨天)就靠这条链路把改稿带回前端。"""
    if not _acquire_lock():
        return {"status": "locked", "added": 0, "message": "已有运行中，跳过。"}
    try:
        et = ZoneInfo("America/New_York")
        d = datetime.strptime(date_str, "%Y-%m-%d").replace(tzinfo=et)
        since = d.astimezone(timezone.utc)
        until = (d + timedelta(days=1)).astimezone(timezone.utc)
        raw = asyncio.run(news_query_multi(
            types=EDITORIAL_TYPES, since_utc=since, until_utc=until,
            limit=500, max_pages=12, sentiments=None, include_body=True))
        by_id: dict[str, dict] = {}
        for it in raw:
            nid = str(it.get("NodeID") or it.get("ID"))
            cur = by_id.get(nid)
            if cur is None:
                by_id[nid] = it
            else:
                cur_u = cur.get("UpdatedAt") or cur.get("CreatedAt") or ""
                new_u = it.get("UpdatedAt") or it.get("CreatedAt") or ""
                if new_u > cur_u:
                    by_id[nid] = it
        all_ids = list(by_id.keys())

        md_path, js_path = _day_paths(date_str)
        metas = _load_day(js_path)
        seen = seen_store.load_seen()

        def _ok(it: dict) -> bool:
            if is_noise(it.get("Title") or ""):
                return False
            if sentiment_only and not _has_sentiment(it.get("Sentiment")):
                return False
            return True

        new_kept, updated_kept = _split_new_vs_updated(
            by_id, metas, seen=seen, extra_filter=_ok)
        new_kept.sort(key=lambda x: x.get("CreatedAt") or "", reverse=True)

        render_fn = _render if translate else _render_raw
        run_hhmm = datetime.now().astimezone().strftime("%H:%M")

        new_metas: list[dict] = []
        if new_kept:
            workers = max(1, min(TR_PARALLEL, len(new_kept)))
            with ThreadPoolExecutor(max_workers=workers) as ex:
                new_metas = list(ex.map(render_fn, new_kept))
            for m in new_metas:
                m["added"] = run_hhmm

        updated_count = 0
        if updated_kept:
            workers = max(1, min(TR_PARALLEL, len(updated_kept)))
            with ThreadPoolExecutor(max_workers=workers) as ex:
                updated_metas = list(ex.map(render_fn, updated_kept))
            updated_count = _apply_updated_metas(metas, updated_metas, date_str, run_hhmm)

        if new_metas or updated_count:
            if new_metas:
                metas = metas + new_metas
            _save_day(js_path, metas)
            if WRITE_MD: md_path.write_text(_build_md(date_str, metas), encoding="utf-8")  # .md 默认关闭

        marked = seen_store.mark_seen_updated(
            {nid: by_id[nid].get("UpdatedAt") or "" for nid in all_ids})
        seen_store.prune(max_age_days=14)
        msg = f"{date_str} 全天 +{len(new_metas)}"
        if updated_count:
            msg += f" / 更新 {updated_count}"
        msg += f"（共 {len(metas)}）-> {md_path}"
        return {"status": "ok", "date": date_str, "added": len(new_metas),
                "updated": updated_count, "total": len(metas),
                "file": str(md_path), "message": msg}
    finally:
        try:
            LOCK_PATH.unlink()
        except OSError:
            pass
