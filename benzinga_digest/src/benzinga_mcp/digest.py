def _ensure_ollama_server() -> None:
    """若本地 ollama 服务没起来，尝试后台拉起一次。"""
    global _ollama_started
    if _ollama_started:
        return
    try:
        urllib.request.urlopen("http://localhost:11434/api/tags", timeout=2)
        _ollama_started = True
        return
    except Exception:
        pass
    try:
        subprocess.Popen(["ollama", "serve"],
                         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        for _ in range(15):
            time.sleep(1)
            try:
                urllib.request.urlopen("http://localhost:11434/api/tags", timeout=2)
                _ollama_started = True
                return
            except Exception:
                continue
    except Exception:
        pass


def _ollama_prompt(prompt: str, timeout: int = 300) -> str | None:
    _ensure_ollama_server()
    body = json.dumps({
        "model": OLLAMA_MODEL, "prompt": prompt,
        "stream": False, "options": {"temperature": 0},
    }).encode()
    try:
        req = urllib.request.Request(OLLAMA_URL, data=body,
                                     headers={"Content-Type": "application/json"})
        resp = json.loads(urllib.request.urlopen(req, timeout=timeout).read())
        out = (resp.get("response") or "").strip()
        return out or None
    except Exception:
        return None


def _ollama(text: str) -> str | None:
    return _ollama_prompt(_TR_PROMPT + text)


def qwen_translate_lines(texts: list) -> list:
    """qwen 批量翻译(编号格式 + 行数校验, 不齐则逐条兜底)。返回与输入等长的中文列表。"""
    if not texts:
        return []
    numbered = "\n".join(f"{i + 1}. {t}" for i, t in enumerate(texts))
    prompt = ("把下面每行编号的英文财经新闻翻成简体中文。严格保持相同编号和行数，"
              "每行格式『编号. 译文』，保留股票代码/公司名/数字/百分比不变。"
              "只输出译文行，不要解释：\n\n" + numbered)
    out = _ollama_prompt(prompt)
    if out:
        lines = [re.sub(r"^\s*\d+[.、]\s*", "", ln) for ln in out.strip().split("\n") if ln.strip()]
        if len(lines) == len(texts):
            return [ln.strip() for ln in lines]
    return [translate_title(t) for t in texts]   # 行数不齐 → 逐条兜底


def translate_title(text: str) -> str:
    """标题：本地 qwen 翻译；失败仅回退原文（无其它翻译后端）。"""
    text = (text or "").strip()
    if not text:
        return ""
    return _ollama(text) or text


def translate_body(text: str) -> str:
    """正文：本地 qwen 整篇翻译；失败仅回退原文。"""
    text = (text or "").strip()
    if not text:
        return ""
    return _ollama(text) or text


