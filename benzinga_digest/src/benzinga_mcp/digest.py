_TR_PRIMARIES = ("google", "bing", "argos")
_TR_ALL = ("google", "bing", "argos")    # 全部可用源(顺序即非首选时的兜底优先级)
_TR_CONC = 5                             # 块间并发上限(快,又不突发到限流)

# ── 动态冷却调度:哪家这批翻失败(多半 429/封),就冷却它 N 秒,后续请求**直接跳过**(见
#    translate_lines)→ 真正绕开、不再每轮回戳给限流续命,把活全分给健康的家;冷却到期自动复活。
#    本地 argos 永远兜底,所以就算三家远程全冷却也不会翻空。45s 太短(到期立刻被回戳)→ 拉到 3min。
_TR_COOL_SECS = 180
_tr_cooldown: dict = {}
_tr_cd_lock = threading.Lock()


def _tr_cooled(prov: str) -> bool:
    with _tr_cd_lock:
        return _tr_cooldown.get(prov, 0) > time.time()


def _tr_cool(prov: str) -> None:
    with _tr_cd_lock:
        _tr_cooldown[prov] = time.time() + _TR_COOL_SECS


def _tr_provider(provider: str, texts: list) -> list:
    """用一家翻一批:按这家容量切块 + 块间并发翻。返回与输入**等长**的 list,失败的块那几格留
    None(交上层用下一家**只补没成的**)。Google 一次吃 28KB → 大批量也就 1-3 块。这批有块失败
    → 冷却该家。"""
    fn, cap = _TR_FNS[provider], _TR_CAP[provider]
    spans, i, n = [], 0, len(texts)          # (起始下标, 该块文本)
    while i < n:
        s = i; c, clen = [], 0
        while i < n and (not c or clen + len(texts[i] or "") + len(_BING_SEP) < cap):
            c.append(texts[i]); clen += len(texts[i] or "") + len(_BING_SEP); i += 1
        spans.append((s, c))
    out = [None] * n
    failed = False
    with ThreadPoolExecutor(max_workers=min(_TR_CONC, len(spans))) as ex:
        for s, r in ex.map(lambda sp: (sp[0], fn(sp[1])), spans):
            if r is not None:
                for j, zh in enumerate(r):
                    out[s + j] = zh
            else:
                failed = True
    if failed:
        _tr_cool(provider)                   # 多半被限流/封 → 冷却,后续先绕开
    return out


# ── 轻量本地兜底:隔离的 .venv_opus 子进程跑 argos ct2 NMT(~50 条/秒、基本不转风扇,
#    远比 qwen 3B LLM 轻)。隔离=崩了只崩子进程→自动退回 qwen,绝不影响 PWA 主服务。
_ARGOS_BASE = Path(__file__).resolve().parents[2]
_ARGOS_PY = str(_ARGOS_BASE / ".venv_opus" / "bin" / "python")
_ARGOS_WORKER = str(_ARGOS_BASE / "argos_worker.py")


# ── 常驻 worker:模型只在首次启动时加载一次(~326ms),之后每次调用免重载(单篇/SEC 逐块从
#    ~330ms 降到 ~10-50ms)。单进程 + 锁串行(一次一批);崩了→杀掉重启一次重试,再不行 30s 内
#    跳过(返 None 交远程)。父进程退出→stdin EOF,worker 自动结束(atexit 再兜一道)。
_argos_proc: dict = {"p": None, "fail_until": 0.0}
_argos_lock = threading.Lock()


def _argos_start():
    """启动一个常驻 argos worker 子进程(serve 模式)。环境缺失/启动失败→None。"""
    if not (os.path.exists(_ARGOS_PY) and os.path.exists(_ARGOS_WORKER)):
        return None
    try:
        return subprocess.Popen(
            [_ARGOS_PY, _ARGOS_WORKER, "serve"],
            stdin=subprocess.PIPE, stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL, text=True, bufsize=1)
    except Exception as e:
        _tr_note("argos", "spawn: %s" % str(e)[:120])
        return None


def _argos_io(p, payload: str, timeout: float) -> str:
    """给常驻 worker 写一行请求、读一行响应(硬超时:卡住就放弃,由上层杀进程重启)。"""
    box: dict = {}

    def _run():
        try:
            p.stdin.write(payload + "\n")
            p.stdin.flush()
            box["line"] = p.stdout.readline()
        except Exception as e:
            box["err"] = e

    th = threading.Thread(target=_run, daemon=True)
    th.start()
    th.join(timeout)
    if th.is_alive():
        raise TimeoutError("argos worker timeout")
    if "err" in box:
        raise box["err"]
    return box.get("line") or ""


def _argos_translate(texts: list):
    """常驻 argos worker 翻一批(en→简中)。本地零封禁→不进冷却;失败返 None(上层用远程家补)。"""
    if not texts:
        return []
    if time.time() < _argos_proc["fail_until"]:    # 最近刚失败 → 短暂跳过,别反复 spawn
        return None
    payload = json.dumps({"texts": texts}, ensure_ascii=False)
    timeout = max(20.0, len(texts) * 0.1 + 15.0)   # 首次含模型加载;大批量留足
    with _argos_lock:
        for _ in range(2):                         # 至多重启一次重试
            p = _argos_proc["p"]
            if p is None or p.poll() is not None:  # 没起/已死 → 起一个
                p = _argos_start()
                _argos_proc["p"] = p
                if p is None:
                    break
            try:
                line = _argos_io(p, payload, timeout)
                obj = json.loads(line) if line.strip() else {}
                zh = obj.get("zh")
                if isinstance(zh, list) and len(zh) == len(texts):
                    _tr_note("argos")
                    return [z if z else None for z in zh]
                _tr_note("argos", obj.get("err") or "worker 无有效输出")
            except Exception as e:
                _tr_note("argos", "%s: %s" % (type(e).__name__, str(e)[:120]))
            try:                                   # 本轮失败 → 杀掉,下一轮重启重试
                if p:
                    p.kill()
            except Exception:
                pass
            _argos_proc["p"] = None
        _argos_proc["fail_until"] = time.time() + 30.0   # 两次都失败 → 30s 内不再尝试
    return None


@atexit.register
def _argos_shutdown() -> None:
    p = _argos_proc.get("p")
    if p and p.poll() is None:
        try:
            p.terminate()
        except Exception:
            pass


def _tr_dispatch(prov: str, texts: list) -> list:
    """用一家翻一批,返回**等长** list(失败格留 None)。argos=本地子进程(整批、不切块、不冷却,
    自带 _tr_note);google/bing=远程按容量切块 + 块间并发(失败则冷却该家)。"""
    if prov == "argos":
        r = _argos_translate(texts)               # 本地零封禁→不进冷却;失败/缺环境返 None
        return r if r is not None else [None] * len(texts)
    return _tr_provider(prov, texts)


def _tr_looks_gibberish(en: str, zh: str) -> bool:
    """检测翻译退化(argos/qwen/google 遇到短+缩写多+数字混排/长文本时,seq2seq 陷 repetition
    loop 或复读整句)。命中即视为翻译失败,让 translate_lines 走下一家 provider。

    检测口径(任一命中即 True):
      1) 长度爆炸(仅 en 有意义时): zh 字符数 > max(80, 5 × en 字符数)
      2) 2-字 / 3-字 n-gram 高频: 最高频 n-gram 出现 ≥ 8 次
      3) 单一 n-gram 覆盖率: 某 n-gram 覆盖译文 ≥ 40% 有效字符
      4) 4-字 n-gram 局部密集: 出现 ≥ 3 次(短段「, 半价, 半价, 半价」类)
      5) 长子串复读: 8-字子串 ≥ 3 次 / 12-字子串 ≥ 2 次(整句复读机)
    """
    if not zh:
        return False
    zh_c = "".join(zh.split())
    if len(zh_c) < 15:
        return False
    # 1) 长度爆炸 — 只有 en 参考才启用, 避免扫历史缓存时无 en 全被误伤
    en_c = "".join((en or "").split())
    if len(en_c) >= 10 and len(zh_c) > max(80, 5 * len(en_c)):
        return True
    # 2/3) 2/3-字 n-gram 高频 + 覆盖率
    from collections import Counter
    for n in (2, 3):
        if len(zh_c) < n * 3:
            continue
        cnts = Counter(zh_c[i:i + n] for i in range(len(zh_c) - n + 1))
        if not cnts:
            continue
        _, top_cnt = cnts.most_common(1)[0]
        if top_cnt >= 8:
            return True
        if top_cnt * n / len(zh_c) > 0.4:
            return True
    # 4) 4-字 n-gram 短段狂欢: ≥ 3 次 且 至少一对相邻 gap ≤ 8 (紧邻狂欢, 如「, 半价, 半价」)
    #    列表模式(如「#1 = X, #2 = X, #3 = X」) gap 通常 ≥ 15, 会被此规则豁免
    from collections import defaultdict
    if len(zh_c) >= 12:
        pos4: dict = defaultdict(list)
        for i in range(len(zh_c) - 3):
            pos4[zh_c[i:i + 4]].append(i)
        for gram, ps in pos4.items():
            if len(ps) < 3:
                continue
            tight = any(ps[j] - ps[j - 1] <= 8 for j in range(1, len(ps)))
            if tight:
                return True
    # 5) 长子串复读机: 8/12-gram 出现 ≥ 2 次 且 相隔 gap ≥ 80 字
    #    (整句在段内被复读, 中间夹别的内容); 紧邻 gap < 80 视为列表/术语复用不触发
    if len(zh_c) >= 24:
        pos8: dict = defaultdict(list)
        for i in range(len(zh_c) - 7):
            pos8[zh_c[i:i + 8]].append(i)
        for gram, ps in pos8.items():
            if len(ps) < 2:
                continue
            max_gap = max(ps[j] - ps[j - 1] for j in range(1, len(ps)))
            if max_gap >= 80:
                return True
    return False


def _tr_looks_untranslated(en: str, zh: str) -> bool:
    """检测"英翻英"——翻译结果仍是英文、没有中文字符。命中则视为翻译失败,让下一家 provider 重试。"""
    if not zh or not en:
        return False
    en_s = " ".join(en.split()).strip()
    if len(en_s) < 10:
        return False
    zh_s = " ".join(zh.split()).strip()
    if zh_s.lower() == en_s.lower():
        return True
    cjk = sum(1 for c in zh if ("一" <= c <= "鿿" or "㐀" <= c <= "䶿"))
    if cjk == 0:
        return True
    if len(en_s) > 50 and len(zh_s) > 20 and cjk / len(zh_s) < 0.1:
        return True
    return False


def translate_lines(texts: list) -> list:
    """批量英→简中:**google(translate-pa)/bing/argos 三家轮换当首选**(每次调用换一家、分摊负载→
    任一端点都到不了限流;UA 也每请求轮换),**冷却中的远程家直接跳过**,**只把没翻成的**顺次交其它
    家补。argos 本地零封禁=永远在列兜底,故三家就算远程全冷却也不翻空,极端才留英文原文(不再转
    风扇 qwen)。返回与输入等长的中文列表。SEC 财报双语 + digest 全走这条。

    额外:每家返回后过 _tr_looks_gibberish 过滤(argos seq2seq 遇 PMI 类缩写常吐出重复退化文本
    → 视为失败让下一家翻;全家都退化 → 保底留原文)。"""
    if not texts:
        return []
    primary = _TR_PRIMARIES[_tr_turn[0] % len(_TR_PRIMARIES)]
    _tr_turn[0] += 1
    base = [primary] + [p for p in _TR_ALL if p != primary]
    order = [p for p in base if not _tr_cooled(p)]   # 冷却中的远程家直接跳过(argos 从不冷却→永远在列)
    out = [None] * len(texts)
    pending = list(range(len(texts)))
    for prov in order:
        if not pending:
            break
        sub = [texts[i] for i in pending]
        res = _tr_dispatch(prov, sub)
        nxt = []
        for k, idx in enumerate(pending):
            zh = res[k]
            if zh is not None and not _tr_looks_gibberish(texts[idx], zh) and not _tr_looks_untranslated(texts[idx], zh):
                out[idx] = zh
            else:
                nxt.append(idx)
        pending = nxt
    for idx in pending:                       # 全失败的极少数 → 留英文原文(已去掉 qwen,不再转风扇)
        out[idx] = texts[idx]
    return out


