def is_noise(title: str) -> bool:
    if not title:
        return False
    return bool(SKIP_TITLE.search(title) or ANALYST_TITLE.search(title))


def extract_images(body_html: str) -> list[str]:
    if not body_html:
        return []
    urls = re.findall(r'<img[^>]+src=["\']([^"\']+)["\']', body_html)
    seen, out = set(), []
    for u in urls:
        if u not in seen:
            seen.add(u)
            out.append(html.unescape(u))
    return out


def extract_links(body_html: str) -> list[str]:
    if not body_html:
        return []
    hrefs = re.findall(r'<a[^>]+href=["\']([^"\']+)["\']', body_html)
    seen, out = set(), []
    for h in hrefs:
        h = html.unescape(h)
        if h.startswith("http") and h not in seen:
            seen.add(h)
            out.append(h)
    return out[:6]


def trim_promo(text: str) -> str:
    if not text:
        return ""
    cut = len(text)
    for marker in PROMO_CUT:
        i = text.find(marker)
        if i != -1 and i < cut:
            cut = i
    return text[:cut].strip()


