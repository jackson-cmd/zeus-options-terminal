def _google_tr_chunk(texts: list) -> list | None:
    """一次 Google translate-pa 批量翻译(英→简中)。数组天然对齐、批量友好,基本不限流。
    返回等长 list；失败/429/条数不符→None。"""
    key = _gpa_key()
    if not key:
        _tr_note("google", "未配置 Google 翻译 key(可选) / no Google translate key set (optional)")
        return None
    arr = [(t or "").replace("\n", " ").strip() or "·" for t in texts]
    body = json.dumps([[arr, "en", "zh-CN"], "wt_lib"], ensure_ascii=False).encode("utf-8")
    try:
        req = urllib.request.Request(
            "https://translate-pa.googleapis.com/v1/translateHtml", data=body, headers={
                "User-Agent": _rand_ua(), "Content-Type": "application/json+protobuf",
                "X-Goog-API-Key": key, "Accept": "*/*",
                "Accept-Language": _rand_lang(),
                "Referer": "https://translate.google.com/"})
        resp = json.loads(urllib.request.urlopen(req, timeout=30).read().decode("utf-8"))
        out = resp[0] if (isinstance(resp, list) and resp) else None
        if isinstance(out, list) and len(out) == len(texts):
            _tr_note("google")
            return [html.unescape((s or "").strip()) for s in out]
        _tr_note("google", "返回条数不符")
    except Exception as e:
        _tr_note("google", "%s: %s" % (type(e).__name__, str(e)[:120]))
    return None


# ─── Bing 免 key 翻译(google/bing/argos 轮替之一) ────────────────────────────────
# Bing translator 网页端 /ttranslatev3 免 key:先爬首页拿 IG/key/token(TTL≈1h),
# 再 POST 单段文本。⚠️ Bing 会吃掉 \n,但保留 " ||| " 分隔符 → 用它批量后拆回校验。
# 单次长度有限(~1k 字符),故 Bing 块更小。任何失败 → 返 None,上层轮替到其它家。
# UA 每次刷 token 时换一张脸(token 与 UA 同生命周期保持一致,避免会话指纹自相矛盾)。
_BING_SEP = " ||| "
_BING_MAX = 1000
_bing_state: dict = {"ig": None, "key": None, "token": None, "at": 0.0, "ua": None}
_bing_lock = threading.Lock()


def _bing_refresh() -> None:
    ua = _rand_ua()
    req = urllib.request.Request("https://www.bing.com/translator", headers={"User-Agent": ua})
    html = urllib.request.urlopen(req, timeout=15).read().decode("utf-8", "replace")
    ig = re.search(r'IG:"([0-9A-Fa-f]+)"', html)
    ah = re.search(r'params_AbusePreventionHelper\s*=\s*\[\s*(\d+)\s*,\s*"([^"]+)"', html)
    if not (ig and ah):
        raise RuntimeError("bing token scrape failed")
    _bing_state.update(ig=ig.group(1), key=ah.group(1), token=ah.group(2), at=time.time(), ua=ua)


def _bing_creds():
    with _bing_lock:
        if not _bing_state["token"] or (time.time() - _bing_state["at"] > 540):   # 9min 内复用(TTL 1h)
            _bing_refresh()
        return _bing_state["ig"], _bing_state["key"], _bing_state["token"], _bing_state["ua"]


def _bing_tr_chunk(texts: list) -> list | None:
    """一次 Bing 免 key 批量(" ||| " 分隔)英→简中。返回等长 list；失败/行数不符→None。"""
    if not texts:
        return []
    try:
        ig, key, token, ua = _bing_creds()
    except Exception as e:
        _tr_note("bing", "token: %s" % str(e)[:80])
        return None
    q = _BING_SEP.join(((t or "").replace("\n", " ").replace("|", "/").strip() or "·") for t in texts)
    url = f"https://www.bing.com/ttranslatev3?isVertical=1&IG={ig}&IID=translator.5023"
    data = urllib.parse.urlencode({"fromLang": "en", "to": "zh-Hans",
                                   "text": q, "token": token, "key": key}).encode()
    try:
        req = urllib.request.Request(url, data=data, headers={
            "User-Agent": ua, "Content-Type": "application/x-www-form-urlencoded",
            "Accept-Language": _rand_lang(),
            "Referer": "https://www.bing.com/translator", "Origin": "https://www.bing.com"})
        resp = json.loads(urllib.request.urlopen(req, timeout=20).read().decode("utf-8"))
        tr = resp[0]["translations"][0]["text"]
        parts = [p.strip() for p in tr.split("|||")]
        if len(parts) == len(texts):
            _tr_note("bing")
            return parts
        _tr_note("bing", "分隔/行数不符")
    except Exception as e:
        _tr_note("bing", "%s: %s" % (type(e).__name__, str(e)[:120]))
        with _bing_lock:                       # token 可能过期 → 下次强制重爬
            _bing_state["token"] = None
    return None


def _urlopen_hard(req, soft_timeout: int, hard_timeout: int) -> bytes:
    """硬超时包装：即使底层 SSL 读忽略 socket 超时(已实测会发生)，也保证调用方
    绝不阻塞超过 hard_timeout。超时则放弃该 daemon 线程(进程退出自动回收)并抛
    TimeoutError，交上层用新连接重试。成功返回响应 body(bytes)；HTTPError 等异常原样上抛。"""
    box: dict = {}

    def _run():
        try:
            box["r"] = urllib.request.urlopen(req, timeout=soft_timeout).read()
        except BaseException as e:  # 含 HTTPError，回传给上层按 429/5xx 处理
            box["e"] = e

    th = threading.Thread(target=_run, daemon=True)
    th.start()
    th.join(hard_timeout)
    if th.is_alive():
        raise TimeoutError(f"hard timeout after {hard_timeout}s")
    if "e" in box:
        raise box["e"]
    return box["r"]


def openai_translate_lines(texts: list, model: str, key: str, timeout: int = 12):
    """OpenAI 批量英→简中(JSON 模式保对齐)。返回 (list|None, prompt_tok, completion_tok)。"""
    if not texts or not key:
        return None, 0, 0
    sys_p = ("You are a professional translator. Translate each English financial-news "
             "string to Simplified Chinese. Keep tickers, company names, person names, "
             "numbers and % unchanged. Return ONLY JSON {\"t\":[...]} where t is an array "
             "of translations in the SAME order and SAME length as the input array 'src'.")
    payload = json.dumps({
        "model": model, "temperature": 0,
        "response_format": {"type": "json_object"},
        "messages": [{"role": "system", "content": sys_p},
                     {"role": "user", "content": json.dumps({"src": texts}, ensure_ascii=False)}],
    }).encode()
    # 429/5xx → 读 Retry-After 退避重试(限流瞬时, 值得等)。
    # 超时/网络失败 → 仅 1 次轻重试后立即放弃(pt=0), 交上层退回本地 opus。
    # 绝不久等: 历史"卡死"正是"久等 × 上层二分"把一次抖动指数级放大成数小时。
    for attempt in range(3):
        req = urllib.request.Request(
            "https://api.openai.com/v1/chat/completions", data=payload,
            headers={"Authorization": "Bearer " + key, "Content-Type": "application/json"})
        try:
            resp = json.loads(_urlopen_hard(req, timeout, timeout + 10).decode("utf-8"))
            usage = resp.get("usage", {})
            pt, ct = usage.get("prompt_tokens", 0), usage.get("completion_tokens", 0)
            arr = json.loads(resp["choices"][0]["message"]["content"]).get("t")
            if isinstance(arr, list) and len(arr) == len(texts):
                return [str(x) for x in arr], pt, ct
            return None, pt, ct          # 对齐失败(有响应, pt>0)→ 上层二分细化
        except urllib.error.HTTPError as e:
            if e.code == 429 or e.code >= 500:
                ra = e.headers.get("Retry-After")
                wait = float(ra) if (ra and ra.replace(".", "").isdigit()) else min(20, 2 ** attempt)
                time.sleep(wait + 0.5)
                continue                 # 限流/服务端错 → 退避重试
            return None, 0, 0            # 其它 4xx → 放弃(pt=0, 不二分)
        except Exception:
            return None, 0, 0            # 超时/网络: 立即放弃(pt=0)→ 上层秒退本地 opus
                                         # (持续 wedge 由 backfill 的 _wedge_watchdog 自重启逃逸)
    return None, 0, 0                    # 重试耗尽(pt=0, 不二分)


